public class operator {
    public static void main(String[] args) {
        int a = 5;
        int b = 3;
        System.out.println("a | b = " + (a | b));
        System.out.println("Logical OR = " + (a > 3 || b > 5));
        System.out.println("a & b = " + (a & b));
        System.out.println("Logical AND = " + (a > 3 && b > 2));
    }
}